/** 按关键词检索本地条文（命中 tags / title / text 任一即返回）。 */
function searchLocalStatutes(keyword) {
  if (!keyword) return [];
  const k = String(keyword).trim();
  if (!k) return [];
  return STATUTES.filter(
    (s) =>
      s.tags.some((t) => t.includes(k) || k.includes(t)) ||
      s.title.includes(k) ||
      s.text.includes(k)
  );
}

function getStatuteByCode(code) {
  return STATUTES.find((s) => s.code === code) || null;
}

